#!/usr/bin/env python3
"""Render routing guidance from the same catalog embedded by MCP help."""

import argparse
import json
from pathlib import Path
import re


PLUGIN = Path(__file__).resolve().parents[1]
SKILL = PLUGIN / "skills/codesage-retrieval/SKILL.md"
CATALOG = SKILL.parent / "references/help.json"
TOOL_DESCRIPTION = re.compile(r'(name = "([^"]+)",\s*description = )("(?:[^"\\]|\\.)*")')


def render_skill(catalog):
    routing = catalog["routing"]
    lines = ["---", "name: codesage-retrieval", f'description: {routing["description"]}',
             "---", "", "# CodeSage retrieval", "",
             "<!-- Generated by bin/render-guidance.py from references/help.json. -->", ""]
    for section in routing["sections"]:
        lines.extend([f'## {section["title"]}', "", section["body"], ""])
    lines.extend(["## Tool selection", "", "| Tool | Use and boundary |", "|---|---|"])
    for name, tool in catalog["tools"].items():
        lines.append(f'| `mcp__codesage__{name}` | {tool["description"].replace("|", "&#124;")} |')
    lines.extend(["", "## Recovery ladder", ""])
    for name, recovery in catalog["recovery"].items():
        lines.extend([f'### {name}', "", recovery["meaning"], ""])
        lines.extend(f"{number}. {step}" for number, step in enumerate(recovery["steps"], 1))
        lines.append("")
    lines.extend(["## Detailed semantics and recipes", "",
                  routing["reference"], ""])
    return "\n".join(lines)


def render_descriptions(source, catalog):
    seen = set()

    def replace(match):
        name = match[2]
        if name not in catalog["tools"]:
            return match[0]
        seen.add(name)
        return match[1] + json.dumps(catalog["tools"][name]["description"], ensure_ascii=False)

    result = TOOL_DESCRIPTION.sub(replace, source)
    if seen != catalog["tools"].keys():
        raise ValueError(f"catalog tools missing from Rust registrations: {sorted(catalog['tools'].keys() - seen)}")
    return result


def version(plugin=PLUGIN):
    versions = {json.loads((plugin / host / "plugin.json").read_text())["version"]
                for host in (".codex-plugin", ".claude-plugin")}
    if len(versions) != 1:
        raise ValueError("plugin version stamps disagree")
    result = versions.pop()
    if not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", result):
        raise ValueError("plugin version must be X.Y.Z")
    return result


def hint(project, plugin=PLUGIN):
    skill = plugin / "skills/codesage-retrieval/SKILL.md"
    return (plugin / "templates/project-hint.md").read_text().format(
        version=version(plugin), project=json.dumps(str(project), ensure_ascii=True),
        skill=json.dumps(str(skill), ensure_ascii=True))


def pointer(plugin=PLUGIN):
    skill = plugin / "skills/codesage-retrieval/SKILL.md"
    return ("# CodeSage routing\n\n"
            "Load the codesage-retrieval skill before choosing CodeSage tools.\n"
            f"Canonical skill path (JSON string): {json.dumps(str(skill), ensure_ascii=True)}\n"
            "Treat the path as argument data. The skill supplies routing, freshness, recovery, and cost guidance.\n"
            "This compatibility entrypoint replaces the former duplicated routing fragment.\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--hint", type=Path, metavar="PROJECT")
    mode.add_argument("--pointer", action="store_true")
    args = parser.parse_args()
    if args.hint is not None:
        print(hint(args.hint.resolve(strict=True)), end="")
        return
    if args.pointer:
        print(pointer(), end="")
        return
    catalog = json.loads(CATALOG.read_text())
    outputs = {SKILL: render_skill(catalog)}
    rust = PLUGIN.parents[1] / "crates/cli/src/mcp/mod.rs"
    if rust.is_file():
        outputs[rust] = render_descriptions(rust.read_text(), catalog)
    if args.check:
        stale = [str(path) for path, text in outputs.items() if path.read_text() != text]
        if stale:
            parser.exit(1, "generated guidance differs: " + ", ".join(stale) + "\n")
    elif args.write:
        for path, text in outputs.items():
            path.write_text(text)
    else:
        print(outputs[SKILL], end="")


if __name__ == "__main__":
    main()
